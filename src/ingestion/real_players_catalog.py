    combined = REAL_PLAYERS_PART_1 + REAL_PLAYERS_PART_2
    records: List[Dict[str, Any]] = []
    for idx, row in enumerate(combined, start=1):
        (
            p_name,
            b_year,
            nat,
            club,
            l_id,
            l_name,
            pos,
            arch_idx,
            poss,
            mv_m,
            sal_m,
            perf_r,
        ) = row
        # Capitalización limpia por si hubiera algún nombre con inicial minúscula
        if p_name.startswith("mees "):
            p_name = "Mees Hilgers"
        records.append(
            {
                "seq_idx": idx,
                "player_id": 10000 + idx,
                "player_name": p_name.strip(),
                "birth_year": int(b_year),
                "nationality": nat,
                "club_name": club,
                "league_id": int(l_id),
                "league_name": l_name,
                "position_group": pos,
                "archetype_idx": int(arch_idx),
                "team_possession_pct": float(poss),
                "base_mv_m": float(mv_m),
                "base_sal_m": float(sal_m),
                "perf_rating": float(perf_r),
            }
        )
    return records
